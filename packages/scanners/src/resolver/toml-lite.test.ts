import { describe, expect, it } from 'vitest'
import { parseArrayOfTables, parseArrayTableEntries, parseTomlDocument, parseTomlSections, tomlArray, tomlKeyPath, tomlString, tomlTable } from './toml-lite'

// Scoped to the TOML the resolvers read: headers, arrays (across lines) and inline tables in Cargo.lock,
// poetry.lock, uv.lock, pyproject.toml and Cargo.toml. The tests below pin the supported subset AND what
// it skips rather than guesses at.

const CARGO = `# This file is automatically @generated by Cargo.
version = 3

[[package]]
name = "anyhow"
version = "1.0.86"
source = "registry+https://github.com/rust-lang/crates.io-index"
checksum = "b3d1d046238990b9cf5bcde22a3fb3584ee5cf65fb2765f454ed428c7a0063da"

[[package]]
name = "clap"
version = "4.5.4"
dependencies = [
 "clap_builder",
 "clap_derive",
]

[[package]]
name = "libc"
version = "0.2.155"
`

describe('parseArrayOfTables', function () {
    it('extracts one entry per array header', function () {
        const tables = parseArrayOfTables(CARGO, 'package')
        expect(tables.map(function name(t) { return t.name })).toEqual(['anyhow', 'clap', 'libc'])
    })

    it('strips quotes from scalar values', function () {
        const tables = parseArrayOfTables(CARGO, 'package')
        expect(tables[0]?.version).toBe('1.0.86')
        expect(tables[0]?.source).toBe('registry+https://github.com/rust-lang/crates.io-index')
    })

    it('ignores keys outside any array-of-tables entry', function () {
        const tables = parseArrayOfTables(CARGO, 'package')
        expect(tables.some(function hasVersionThree(t) { return t.version === '3' })).toBe(false)
    })

    it('returns an empty list when the table name never appears', function () {
        expect(parseArrayOfTables(CARGO, 'metadata')).toEqual([])
    })

    it('returns an empty list for empty input', function () {
        expect(parseArrayOfTables('', 'package')).toEqual([])
    })

    // Cargo.lock writes its dependency lists one per line; those edges are the graph.
    it('reads a multi-line array', function () {
        const tables = parseArrayOfTables(CARGO, 'package')
        expect(tables[1]?.dependencies).toEqual(['clap_builder', 'clap_derive'])
    })

    it('reads a single-line array as a string list', function () {
        const tables = parseArrayOfTables('[[package]]\ndeps = ["a", "b", "c"]\n', 'package')
        expect(tables[0]?.deps).toEqual(['a', 'b', 'c'])
    })

    it('reads an empty single-line array as an empty list', function () {
        const tables = parseArrayOfTables('[[package]]\ndeps = []\n', 'package')
        expect(tables[0]?.deps).toEqual([])
    })

    it('strips a trailing comment', function () {
        const tables = parseArrayOfTables('[[package]]\nname = "serde" # the good one\n', 'package')
        expect(tables[0]?.name).toBe('serde')
    })

    // A `#` inside a quoted value is data, not a comment — hence the quote-aware scanner.
    it('keeps a hash that is inside a quoted string', function () {
        const tables = parseArrayOfTables('[[package]]\nsource = "git+https://x/y#abc"\n', 'package')
        expect(tables[0]?.source).toBe('git+https://x/y#abc')
    })

    it('drops a whole-line comment', function () {
        const tables = parseArrayOfTables('[[package]]\n# a note\nname = "serde"\n', 'package')
        expect(tables[0]).toEqual({ name: 'serde' })
    })

    // A nested header such as [package.dependencies] closes the current entry, so its keys are not
    // folded into the parent — which is what keeps poetry.lock's sub-tables from polluting the package.
    it('closes the current entry at a nested table header', function () {
        const text = '[[package]]\nname = "a"\n\n[package.dependencies]\nfoo = "1.0"\n'
        expect(parseArrayOfTables(text, 'package')).toEqual([{ name: 'a' }])
    })

    it('closes the current entry at a different array header', function () {
        const text = '[[package]]\nname = "a"\n\n[[other]]\nname = "b"\n'
        expect(parseArrayOfTables(text, 'package')).toEqual([{ name: 'a' }])
    })

    it('handles CRLF line endings', function () {
        expect(parseArrayOfTables('[[package]]\r\nname = "a"\r\n', 'package')).toEqual([{ name: 'a' }])
    })

    it('accepts single-quoted values', function () {
        expect(parseArrayOfTables("[[package]]\nname = 'a'\n", 'package')).toEqual([{ name: 'a' }])
    })

    it('leaves a bare unquoted value as-is', function () {
        expect(parseArrayOfTables('[[package]]\noptional = true\n', 'package')).toEqual([{ optional: 'true' }])
    })

    it('ignores a line with no assignment', function () {
        expect(parseArrayOfTables('[[package]]\nname = "a"\ngarbage\n', 'package')).toEqual([{ name: 'a' }])
    })

    it('ignores an assignment with an empty key', function () {
        expect(parseArrayOfTables('[[package]]\n = "a"\nname = "b"\n', 'package')).toEqual([{ name: 'b' }])
    })

    it('keeps the last value when a key repeats', function () {
        expect(parseArrayOfTables('[[package]]\nname = "a"\nname = "b"\n', 'package')).toEqual([{ name: 'b' }])
    })

    it('produces an empty entry for a header with no keys', function () {
        expect(parseArrayOfTables('[[package]]\n', 'package')).toEqual([{}])
    })
})

describe('parseArrayTableEntries', function () {
    const POETRY = `[[package]]
name = "requests"
version = "2.31.0"
files = [
    {file = "requests-2.31.0.tar.gz", hash = "sha256:abc"},
    {file = "requests-2.31.0-py3-none-any.whl", hash = "sha256:def"},
]

[package.dependencies]
certifi = ">=2017.4.17"
"charset-normalizer" = ">=2,<4"
urllib3 = {version = ">=1.21.1,<3", optional = true}

[package.source]
type = "git"

[[package]]
name = "certifi"
version = "2024.2.2"

[metadata]
lock-version = "2.0"
`

    it('attaches each sub-table to the entry it follows', function () {
        const [requests, certifi] = parseArrayTableEntries(POETRY, 'package')
        expect(Object.keys(requests?.sub.dependencies ?? {})).toEqual(['certifi', 'charset-normalizer', 'urllib3'])
        expect(requests?.sub.source).toEqual({ type: 'git' })
        expect(certifi?.sub).toEqual({})
    })

    it('reads an array of inline tables across lines, trailing comma included', function () {
        const [requests] = parseArrayTableEntries(POETRY, 'package')
        expect(requests?.values.files).toEqual([
            { file: 'requests-2.31.0.tar.gz', hash: 'sha256:abc' },
            { file: 'requests-2.31.0-py3-none-any.whl', hash: 'sha256:def' }
        ])
    })

    it('reads an inline table value', function () {
        const [requests] = parseArrayTableEntries(POETRY, 'package')
        expect(requests?.sub.dependencies?.urllib3).toEqual({ version: '>=1.21.1,<3', optional: 'true' })
    })

    it('ends the entries at an unrelated table', function () {
        expect(parseArrayTableEntries(POETRY, 'package')).toHaveLength(2)
    })
})

describe('parseTomlSections', function () {
    it('keeps the keys before the first header in a section of its own', function () {
        const [top, project] = parseTomlSections('version = 1\n\n[project]\nname = "app"\n')
        expect(top).toEqual({ header: '', array: false, values: { version: '1' } })
        expect(project).toEqual({ header: 'project', array: false, values: { name: 'app' } })
    })

    // A key never starts with `[`, so a header whose quoted part holds an `=` is still a header.
    it('reads a header whose quoted part holds an equals sign', function () {
        const sections = parseTomlSections('[target.\'cfg(target_os = "linux")\'.dependencies]\nlibc = "0.2"\n')
        expect(sections[1]?.header).toBe('target.\'cfg(target_os = "linux")\'.dependencies')
    })

    it('reads a multi-line array of strings', function () {
        const [, project] = parseTomlSections('[project]\ndependencies = [\n  "requests>=2",  # http\n  "click",\n]\n')
        expect(project?.values.dependencies).toEqual(['requests>=2', 'click'])
    })

    it('reads escapes in a basic string and none in a literal one', function () {
        const [top] = parseTomlSections('a = "say \\"hi\\"\\tnow\\n"\nb = \'C:\\\\path\'\n')
        expect(top?.values).toEqual({ a: 'say "hi"\tnow\n', b: 'C:\\\\path' })
    })

    it('reads an empty inline table', function () {
        expect(parseTomlSections('a = {}\n')[0]?.values).toEqual({ a: {} })
    })

    it('reads a quoted key', function () {
        expect(parseTomlSections('"my.key" = "v"\n')[0]?.values).toEqual({ 'my.key': 'v' })
    })

    it('reads nested arrays and tables', function () {
        const [top] = parseTomlSections('a = [[1, 2], { b = [3] }]\n')
        expect(top?.values.a).toEqual([['1', '2'], { b: ['3'] }])
    })

    // A value it cannot read is skipped rather than guessed at, and the next line still reads.
    it.each([
        'a = "unterminated',
        'a = [1 2]',
        'a = { b 1 }',
        'a = { = 1 }',
        'a = { b = }',
        'a = { b = 1 c = 2 }',
        'a = [,]',
        'a = "ends in an escape\\',
        'a ='
    ])('skips the unreadable value %j', function (line) {
        expect(parseTomlSections(line + '\nz = "ok"\n')[0]?.values).toEqual({ z: 'ok' })
    })
})

// A dotted key is a table (https://toml.io/en/v1.0.0#keys): `bytes.workspace = true` is `bytes = { workspace = true }`.
describe('dotted keys', function () {
    it('nests a dotted key, merging keys that share a prefix', function () {
        expect(parseTomlSections('bytes.workspace = true\nbytes.features = ["a"]\n')[0]?.values).toEqual({ bytes: { workspace: 'true', features: ['a'] } })
    })

    it('reads quoted segments and spaces around the dots', function () {
        expect(parseTomlSections('"a.b" . \'c\' . d = 1\n')[0]?.values).toEqual({ 'a.b': { c: { d: '1' } } })
    })

    it('nests a dotted key inside an inline table', function () {
        expect(parseTomlSections('a = { b.c = 1, b.d = 2 }\n')[0]?.values).toEqual({ a: { b: { c: '1', d: '2' } } })
    })

    // `a = 1` then `a.b = 2` is not TOML: the second line is skipped, never folded into a guess.
    it('skips a dotted key that runs into a plain value', function () {
        expect(parseTomlSections('a = 1\na.b = 2\n')[0]?.values).toEqual({ a: '1' })
    })

    it('rejects a key with an empty segment', function () {
        expect(parseTomlSections('a. = 1\nz = "ok"\n')[0]?.values).toEqual({ z: 'ok' })
    })

    // Keys come from scanned repositories: `__proto__` is a key like any other, never a prototype.
    it('keeps a __proto__ key as data', function () {
        const [top] = parseTomlSections('__proto__.polluted = "yes"\n')
        expect(Object.keys(top?.values ?? {})).toEqual(['__proto__'])
        expect(({} as Record<string, unknown>).polluted).toBeUndefined()
        expect(Object.keys(parseTomlDocument('[__proto__]\npolluted = "yes"\n[[__proto__.x]]\n'))).toEqual(['__proto__'])
        expect(({} as Record<string, unknown>).polluted).toBeUndefined()
    })
})

describe('tomlKeyPath', function () {
    it('splits a header into its segments', function () {
        expect(tomlKeyPath('target.\'cfg(target_os = "linux")\'.dev-dependencies')).toEqual(['target', 'cfg(target_os = "linux")', 'dev-dependencies'])
    })

    it('is null for text that is not a key', function () {
        expect(tomlKeyPath('a b')).toBeNull()
        expect(tomlKeyPath('a.')).toBeNull()
    })
})

describe('parseTomlDocument', function () {
    it('merges headers, dotted keys and top-level dotted keys into one tree', function () {
        const doc = parseTomlDocument('dev-dependencies.a = "1"\n\n[dependencies]\nb.workspace = true\n\n[dependencies.c]\nversion = "2"\n\n[dependencies.b]\nfeatures = ["x"]\n')
        expect(doc).toEqual({ 'dev-dependencies': { a: '1' }, dependencies: { b: { workspace: 'true', features: ['x'] }, c: { version: '2' } } })
    })

    it('reads a quoted header segment', function () {
        expect(parseTomlDocument('[patch."https://example.test/x".tokio]\npath = "../t"\n')).toEqual({ patch: { 'https://example.test/x': { tokio: { path: '../t' } } } })
    })

    // A `[[a]]` entry is an element of `a`; a following `[a.x]` belongs to the latest element.
    it('reads array-of-tables entries and their sub-tables', function () {
        const doc = parseTomlDocument('[[bin]]\nname = "a"\n\n[[bin]]\nname = "b"\n\n[bin.extra]\nk = 1\n')
        expect(doc).toEqual({ bin: [{ name: 'a' }, { name: 'b', extra: { k: '1' } }] })
    })

    // A header naming a plain value, or an array header naming a table, is not TOML: its section is skipped.
    it('skips a section whose header runs into a value it cannot hold', function () {
        expect(parseTomlDocument('a = 1\n\n[a.b]\nk = 1\n\n[[a]]\nk = 2\n\n[c]\n\n[[c]]\nk = 3\n\n[d e]\nk = 4\n')).toEqual({ a: '1', c: {} })
    })

    it('skips an array header under a plain value', function () {
        expect(parseTomlDocument('a = 1\n\n[[a.b]]\nk = 1\n')).toEqual({ a: '1' })
    })

    // Defined twice, a table holds the keys of both and a plain key keeps its later value, as within one section.
    it('merges a table defined twice', function () {
        expect(parseTomlDocument('[a]\nb.c = 1\n\n[a]\nb.d = 2\n')).toEqual({ a: { b: { c: '1', d: '2' } } })
        expect(parseTomlDocument('[a]\nb.c = 1\n\n[a]\nb = 2\n')).toEqual({ a: { b: '2' } })
    })

    it('reaches no table through an array whose last element is not one', function () {
        expect(parseTomlDocument('a = ["x"]\n\n[a.b]\nk = 1\n')).toEqual({ a: ['x'] })
    })
})

// An array or table that never closes takes every later line with it — the file is not TOML at that
// point — and yields nothing rather than a guess.
it.each(['a = [1, 2', 'a = { b = 1'])('reads nothing from the unterminated %j', function (line) {
    expect(parseTomlSections(line + '\nz = "ok"\n')[0]?.values).toEqual({})
})

describe('toml value helpers', function () {
    it('narrow a value to the shape asked for', function () {
        expect(tomlString('a')).toBe('a')
        expect(tomlString(['a'])).toBeNull()
        expect(tomlString(undefined)).toBeNull()
        expect(tomlArray(['a'])).toEqual(['a'])
        expect(tomlArray('a')).toEqual([])
        expect(tomlTable({ a: 'b' })).toEqual({ a: 'b' })
        expect(tomlTable(['a'])).toBeNull()
        expect(tomlTable('a')).toBeNull()
        expect(tomlTable(undefined)).toBeNull()
    })
})
